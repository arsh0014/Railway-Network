export const getElectrificationCategory = (pct) => {
  if (pct >= 80) return "Fully Electrified";
  if (pct >= 60) return "Substantial";
  if (pct >= 30) return "Moderate";
  if (pct >= 10) return "Low";
  return "Untapped";
};

export const getElectrificationColor = (pct) => {
  if (pct >= 80) return "#0B2A63"; // 80–100% Fully Electrified (Navy)
  if (pct >= 60) return "#2B78C5"; // 60–80% Substantial (Blue)
  if (pct >= 30) return "#F28C28"; // 30–60% Moderate (Orange)
  if (pct >= 10) return "#D9532F"; // 10–30% Low (Orange-Red)
  return "#A71920";                // 0–10% Untapped (Red)
};

